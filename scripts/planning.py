        f"현재 집중: **{status['focus']} — {next(task['title'] for task in tasks if task['id'] == status['focus'])}**.", '',
        f"다음 실행: **{status['next_task']}**. 진행 {sum(value['status']=='in_progress' for value in state.values())}건 / 완료 {completed}건 / 등록 {len(tasks)}건. 제품 완성률을 뜻하지 않는다.", '',
